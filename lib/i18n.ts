export type Dictionary = (typeof dictionaries)["ht"];

export function dictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function errorText(dict: Dictionary, code: string): string {
  const errors = dict.auth.errors as Record<string, string>;
  return errors[code] ?? errors.invalid;
}

export function habitName(dict: Dictionary, habit: { key: string; name: string }): string {
  if (habit.key && habit.key in dict.builtin) {
    return dict.builtin[habit.key as keyof Dictionary["builtin"]];
  }
  return habit.name;
}
